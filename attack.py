"""MITRE ATT&CK technique names and tactics, from the local data file.

data/attack_techniques.json is generated by scripts/update_attack.py from
MITRE's official STIX data and committed, so no network is needed here.
"""

import json
from collections.abc import Iterable
from pathlib import Path

from models import Technique

DATA_PATH = Path(__file__).parent / "data" / "attack_techniques.json"

# Loaded once at import. A missing or broken file is a setup problem, so let
# it fail loudly instead of silently showing no technique names.
_DATA = json.loads(DATA_PATH.read_text())

TECHNIQUES: dict[str, dict] = _DATA["techniques"]
TACTIC_ORDER: list[str] = _DATA["tactic_order"]
ATTACK_VERSION: str = _DATA["attack_version"]


def technique(technique_id: str) -> Technique:
    """Look up a technique by ID. Unknown IDs get a placeholder name."""
    entry = TECHNIQUES.get(technique_id)
    if entry is None:
        return Technique(id=technique_id, name="Unknown technique (not in local ATT&CK data)")
    return Technique(id=technique_id, name=entry["name"], tactics=entry["tactics"])


def order_tactics(tactics: Iterable[str]) -> list[str]:
    """De-duplicate tactics and sort them in kill-chain order."""
    unique = set(tactics)
    known = [t for t in TACTIC_ORDER if t in unique]
    unknown = sorted(unique - set(TACTIC_ORDER))
    return known + unknown
